window._sessionAlerts = [];

function initAuthUI() {
  const session = getSession();
  if (!session.role) return;

  // Fill user bar
  const roleBadge = document.getElementById('user-role-badge');
  const userName  = document.getElementById('user-name');
  const userTitle = document.getElementById('user-title');
  const btnReset  = document.getElementById('btn-reset');
  const btnFraud  = document.getElementById('btn-new-fraud');
  const btnFL     = document.getElementById('btn-fl-round');

  if (roleBadge) {
    roleBadge.textContent = session.role.charAt(0).toUpperCase() + session.role.slice(1);
    roleBadge.setAttribute('data-role', session.role);
  }
  if (userName)  userName.textContent  = session.name  || 'User';
  if (userTitle) userTitle.textContent = session.title || session.role;

  const perms = session.permissions || {};

  // Role-based UI gating
  if (!perms.canReset   && btnReset) { btnReset.style.display = 'none'; }
  if (!perms.canTriggerFraud && btnFraud) { btnFraud.style.display = 'none'; }
  if (!perms.canRunFL   && btnFL)   { btnFL.disabled = true; btnFL.title = 'Admin access required'; btnFL.style.opacity = '0.4'; }

  // Auditor: hide live feed write actions, show audit emphasis
  if (session.role === 'auditor') {
    const flPanel = document.querySelector('.panel-fl');
    if (flPanel) flPanel.style.opacity = '0.6';
  }
}

function logout() {
  sessionStorage.removeItem('fraudshield_session');
  window.location.replace('login.html');
}

// Auto-init
document.addEventListener('DOMContentLoaded', () => {
  initAuthUI();
});
