// EXPORT 2: Session Summary (all fraud alerts)
// ─────────────────────────────────────────────────────────────────────────────
async function exportSessionPDF() {
  const session = getSession();
  const alerts  = window._sessionAlerts || [];
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ unit: 'mm', format: 'a4', compress: true });
  const W = doc.internal.pageSize.getWidth();
  let y;

  y = pdfHeader(doc, 'SESSION FRAUD SUMMARY', `${alerts.length} fraud events detected`);

  // Session info bar
  doc.setFillColor(...PDF_COLORS.panel);
  doc.roundedRect(10, y, W - 20, 14, 2, 2, 'F');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(...PDF_COLORS.text2);
  doc.text(`Analyst: ${session.name || 'Unknown'}  ·  Role: ${session.title || session.role}  ·  Session started: ${session.loginTime ? new Date(session.loginTime).toLocaleString('en-GB') : '—'}`, 16, y + 9);
  y += 20;

  if (alerts.length === 0) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(11);
    doc.setTextColor(...PDF_COLORS.text3);
    doc.text('No fraud events were detected in this session.', W / 2, y + 20, { align: 'center' });
  } else {
    // ── Summary stats ────────────────────────────────────────────────────────
    y = pdfSection(doc, 'Session Statistics', y);
    const totalFraud = alerts.length;
    const zsl  = alerts.filter(a => a.fraud_type === 'fraud_type_3').length;
    const avgAmt = alerts.reduce((s, a) => s + (a.amount || 0), 0) / totalFraud;
    const totalAmt = alerts.reduce((s, a) => s + (a.amount || 0), 0);
    y = pdfKV(doc, 'Total Fraud Events',      totalFraud, y, PDF_COLORS.danger);
    y = pdfKV(doc, 'Zero-Shot (New Type)',     zsl, y, PDF_COLORS.purple);
    y = pdfKV(doc, 'Total Blocked Amount',     `$${totalAmt.toFixed(2)}`, y, PDF_COLORS.danger);
    y = pdfKV(doc, 'Average Fraud Amount',     `$${avgAmt.toFixed(2)}`, y);
    y = pdfKV(doc, 'Report Generated',         new Date().toLocaleString('en-GB'), y);
    y += 4;

    // ── Alert table ───────────────────────────────────────────────────────────
    y = pdfSection(doc, 'Fraud Event Log', y);
    const FRAUD_SHORT = { fraud_type_0:'Type 0', fraud_type_1:'Type 1', fraud_type_2:'Type 2', fraud_type_3:'ZSL ⚡' };
    const COL = [14, 52, 85, 120, 150, 175];
    const HDRS = ['Transaction ID', 'Time', 'Amount', 'Type', 'FL %', 'Risk'];

    // Table header
    doc.setFillColor(...PDF_COLORS.accent);
    doc.roundedRect(10, y, W - 20, 7, 1, 1, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(...PDF_COLORS.white);
    HDRS.forEach((h, i) => doc.text(h, COL[i], y + 5));
    y += 10;

    // Table rows
    for (let i = 0; i < Math.min(alerts.length, 25); i++) {
      const a = alerts[i];
      if (y > 265) {
        pdfFooter(doc, doc.getNumberOfPages(), '?', session);
        doc.addPage();
        y = 20;
      }
      doc.setFillColor(i % 2 === 0 ? 17 : 13, i % 2 === 0 ? 22 : 18, i % 2 === 0 ? 39 : 30);
      doc.roundedRect(10, y - 3, W - 20, 7, 1, 1, 'F');
      doc.setFont('helvetica', a.fraud_type === 'fraud_type_3' ? 'bold' : 'normal');
      doc.setFontSize(7.5);
      const rowColor = a.fraud_type === 'fraud_type_3' ? PDF_COLORS.purple : PDF_COLORS.text2;
      doc.setTextColor(...rowColor);
      doc.text(a.id || '—', COL[0], y + 2);
      doc.text(a.timestamp ? new Date(a.timestamp * 1000).toLocaleTimeString('en-GB') : '—', COL[1], y + 2);
      doc.text(`$${(a.amount || 0).toFixed(2)}`, COL[2], y + 2);
      doc.text(FRAUD_SHORT[a.fraud_type] || a.fraud_type, COL[3], y + 2);
      doc.text(`${((a.fl_probability || 0) * 100).toFixed(1)}%`, COL[4], y + 2);
      doc.text(a.human_explanation?.risk_level?.split(' ')[0] || 'HIGH', COL[5], y + 2);
      y += 7;
    }
    if (alerts.length > 25) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7.5);
      doc.setTextColor(...PDF_COLORS.text3);
      doc.text(`... and ${alerts.length - 25} more events (export individual reports for full detail)`, 14, y + 4);
    }
  }

  pdfFooter(doc, doc.getNumberOfPages(), doc.getNumberOfPages(), session);
  const filename = `FraudShield_Session_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(filename);
}

